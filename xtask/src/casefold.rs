//! `cargo xtask casefold`: generating the table of simple case folding of
//! mikros-casefold from the pinned `CaseFolding.txt` of the Unicode
//! Character Database, its mappings of status C and S.

use anyhow::{Context, Result, bail};
use std::fmt::Write as _;
use std::path::PathBuf;

/// The Unicode version whose case folding the table holds.
const VERSION: &str = "16.0.0";
const URL: &str = "https://www.unicode.org/Public/16.0.0/ucd/CaseFolding.txt";
const SHA256: &str = "6f1f9c588eb4a5c718d9e8f93b782685e5c7fec872cf05e8e6878053599e09bb";

#[derive(clap::Args)]
pub struct Args {}

/// The generated table's path.
fn table() -> PathBuf {
    crate::workspace_root().join("user/lib/casefold/src/table.rs")
}

pub fn run(_args: &Args) -> Result<()> {
    let dir = crate::workspace_root().join("target/sources/unicode");
    std::fs::create_dir_all(&dir)?;
    let source = dir.join(format!("CaseFolding-{VERSION}.txt"));
    crate::fetch::cached(&format!("CaseFolding.txt {VERSION}"), URL, SHA256, &source)?;
    let text = std::fs::read_to_string(&source)?;
    let out = table();
    std::fs::write(&out, generate(&text)?)?;
    println!("wrote    {}", out.display());
    Ok(())
}

/// The mappings of status C and S of `text`, a `CaseFolding.txt`, by
/// code point.
fn mappings(text: &str) -> Result<Vec<(u32, u32)>> {
    let mut out = Vec::new();
    for (n, line) in text.lines().enumerate() {
        let line = line.split('#').next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }
        let fields: Vec<&str> = line.split(';').map(str::trim).collect();
        let [code, status, mapping, ..] = fields[..] else {
            bail!("line {}: too few fields", n + 1);
        };
        if status != "C" && status != "S" {
            continue;
        }
        let parse =
            |s: &str| u32::from_str_radix(s, 16).with_context(|| format!("line {}: {s}", n + 1));
        out.push((parse(code)?, parse(mapping)?));
    }
    out.sort_unstable();
    if out.windows(2).any(|w| w[0].0 == w[1].0) {
        bail!("a code point has two simple foldings");
    }
    Ok(out)
}

/// The source of the table for `text`.
fn generate(text: &str) -> Result<String> {
    let mappings = mappings(text)?;
    let mut out = String::new();
    writeln!(
        out,
        "// @generated by `cargo xtask casefold` from CaseFolding.txt of the Unicode\n\
         // Character Database {VERSION}, which is (c) Unicode, Inc. and is\n\
         // distributed under the Unicode License v3 (SPDX: Unicode-3.0).\n\
         // Do not edit.\n\
         \n\
         /// The Unicode version of the table.\n\
         pub const UNICODE_VERSION: &str = \"{VERSION}\";\n\
         \n\
         /// The simple case foldings, status C and S, by code point.\n\
         pub static FOLDINGS: [(u32, u32); {}] = [",
        mappings.len()
    )?;
    for (from, to) in mappings {
        writeln!(out, "    (0x{from:04X}, 0x{to:04X}),")?;
    }
    writeln!(out, "];")?;
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn keeps_common_and_simple_foldings() {
        let text = "# A comment\n\
                    0041; C; 0061; # LATIN CAPITAL LETTER A\n\
                    00DF; F; 0073 0073; # LATIN SMALL LETTER SHARP S\n\
                    1E9E; F; 0073 0073; # LATIN CAPITAL LETTER SHARP S\n\
                    1E9E; S; 00DF; # LATIN CAPITAL LETTER SHARP S\n\
                    0130; T; 0069; # LATIN CAPITAL LETTER I WITH DOT ABOVE\n";
        assert_eq!(mappings(text).unwrap(), [(0x41, 0x61), (0x1E9E, 0xDF)]);
        let table = generate(text).unwrap();
        assert!(table.contains("[(u32, u32); 2]") && table.contains("(0x1E9E, 0x00DF),"));
    }

    #[test]
    fn refuses_two_foldings_of_one_code_point() {
        assert!(mappings("0041; C; 0061;\n0041; S; 0062;\n").is_err());
    }
}
