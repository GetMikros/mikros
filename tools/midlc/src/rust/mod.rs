//! Rust bindings: a module per library, nested by the parts of its
//! name, and the shared runtime module `__midl`.
//!
//! The generated code uses `::alloc`, so the crate that includes it must
//! declare `extern crate alloc;`.

use crate::layout::Layout;
use crate::model::*;
use std::cell::Cell;
use std::collections::BTreeMap;
use std::fmt::Write;

mod codec;
mod decls;
mod protocol;

/// What generated bindings depend on.
pub struct Options {
    /// The Rust path of the module that wraps the kernel's system calls
    /// for the runtime, such as `mikros_rt::midl`.
    pub kernel: String,
}

const RUNTIME: &str = include_str!("runtime.rs.in");

/// The Rust bindings of every library in `model`.
pub fn generate(model: &Model, options: &Options) -> String {
    let mut out = String::from("// Generated by midlc. Do not edit.\n\n");
    let runtime = RUNTIME.replace("KERNEL", &options.kernel);
    let runtime = runtime
        .lines()
        .skip_while(|l| l.starts_with("//!"))
        .collect::<Vec<_>>()
        .join("\n");
    writeln!(out, "/// What the generated bindings share.\n#[allow(dead_code)]\npub mod __midl {{\n{runtime}\n}}\n").unwrap();
    let mut tree = Tree::default();
    for library in &model.libraries {
        let mut node = &mut tree;
        for part in library.name.split('.') {
            node = node.children.entry(part.to_string()).or_default();
        }
        node.library = Some(library);
    }
    tree.write(model, &mut out, 0);
    out
}

#[derive(Default)]
struct Tree<'a> {
    library: Option<&'a Library>,
    children: BTreeMap<String, Tree<'a>>,
}

impl Tree<'_> {
    fn write(&self, model: &Model, out: &mut String, depth: usize) {
        if let Some(library) = self.library {
            let g = Gen {
                model,
                layout: Layout { model },
                library: &library.name,
                depth,
                counter: Cell::new(0),
            };
            for line in &library.doc {
                writeln!(out, "//! {line}").unwrap();
            }
            for decl in &library.decls {
                g.decl(decl, out);
            }
        }
        for (name, child) in &self.children {
            writeln!(
                out,
                "#[allow(dead_code, non_camel_case_types, clippy::all)]\npub mod {} {{",
                ident(name)
            )
            .unwrap();
            child.write(model, out, depth + 1);
            out.push_str("}\n");
        }
    }
}

/// What generating one library's bindings needs.
pub(crate) struct Gen<'a> {
    model: &'a Model,
    layout: Layout<'a>,
    /// The library being generated, and how deep its module is.
    library: &'a str,
    depth: usize,
    /// For fresh variable names.
    counter: Cell<u32>,
}

impl Gen<'_> {
    /// The path of the runtime module from this library's module.
    fn rt(&self) -> String {
        format!("{}__midl", "super::".repeat(self.depth))
    }

    /// The Rust path of the declaration with full name `full`.
    fn path(&self, full: &str) -> String {
        let (library, name) = full.rsplit_once('.').expect("full names have a library");
        if library == self.library {
            return name.to_string();
        }
        let parts: Vec<String> = library.split('.').map(ident).collect();
        format!(
            "{}{}::{name}",
            "super::".repeat(self.depth),
            parts.join("::")
        )
    }

    fn decl_of(&self, full: &str) -> &DeclKind {
        &self.model.decl(full).expect("checked names exist").kind
    }

    fn fresh(&self, base: &str) -> String {
        let n = self.counter.get();
        self.counter.set(n + 1);
        format!("{base}{n}")
    }

    fn size(&self, ty: &Type) -> u64 {
        self.layout.shape(ty).size
    }
}

/// `name` as a Rust identifier, escaped when it is a keyword.
pub(crate) fn ident(name: &str) -> String {
    const KEYWORDS: [&str; 39] = [
        "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum",
        "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move",
        "mut", "pub", "ref", "return", "static", "struct", "trait", "true", "type", "unsafe",
        "use", "where", "while", "abstract", "box", "gen", "try",
    ];
    match name {
        "self" | "super" | "Self" | "crate" => format!("{name}_"),
        _ if KEYWORDS.contains(&name) => format!("r#{name}"),
        _ => name.to_string(),
    }
}

/// `NOT_FOUND` as `NotFound`, `point` as `Point`, and `GetInfo`
/// unchanged.
pub(crate) fn camel(name: &str) -> String {
    name.split('_')
        .filter(|p| !p.is_empty())
        .map(|p| {
            let upper = !p.chars().any(|c| c.is_ascii_lowercase());
            let mut chars = p.chars();
            let first = chars.next().map(|c| c.to_ascii_uppercase());
            let rest = chars.map(|c| if upper { c.to_ascii_lowercase() } else { c });
            first.into_iter().chain(rest).collect::<String>()
        })
        .collect()
}

/// `Spawn` as `spawn`, and `GetInfo` as `get_info`.
pub(crate) fn snake(name: &str) -> String {
    let mut out = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 && !out.ends_with('_') {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

/// `doc` as `///` lines indented by `indent`.
pub(crate) fn doc(doc: &[String], indent: &str) -> String {
    doc.iter().map(|l| format!("{indent}/// {l}\n")).collect()
}
