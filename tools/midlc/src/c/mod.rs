//! C bindings (MIKSPEC-0024.R18): the shared runtime `runtime.h`, and a
//! header per library named after it, such as `mikros.gpu.h`, which
//! include each other as `<mikros/midl/...>`.
//!
//! The C names of a library's declarations start with the library's
//! name, its dots made underscores: `mikros.gpu.Render` is
//! `mikros_gpu_Render`.

use crate::layout::Layout;
use crate::model::*;
use std::cell::Cell;
use std::collections::BTreeSet;
use std::fmt::Write;

mod codec;
mod decls;

const RUNTIME: &str = include_str!("runtime.h.in");

/// The headers of the libraries in `model` and the runtime, each as its
/// file name and contents.
pub fn generate(model: &Model) -> Vec<(String, String)> {
    let mut files = vec![("runtime.h".to_string(), RUNTIME.to_string())];
    for library in &model.libraries {
        let g = Gen {
            model,
            layout: Layout { model },
            library,
            counter: Cell::new(0),
        };
        files.push((format!("{}.h", library.name), g.header()));
    }
    files
}

/// What generating one library's header needs.
pub(crate) struct Gen<'a> {
    model: &'a Model,
    layout: Layout<'a>,
    library: &'a Library,
    /// For fresh variable names.
    counter: Cell<u32>,
}

impl Gen<'_> {
    fn header(&self) -> String {
        let library = &self.library.name;
        let guard = format!("MIKROS_MIDL_{}_H", library.replace('.', "_").to_uppercase());
        let mut out = format!(
            "/* Generated by midlc. Do not edit. */\n\n/* The C bindings of the MIDL library {library}.\n"
        );
        for line in &self.library.doc {
            writeln!(out, " * {}", comment(line)).unwrap();
        }
        writeln!(
            out,
            " */\n\n#ifndef {guard}\n#define {guard}\n\n#include <mikros/midl/runtime.h>"
        )
        .unwrap();
        for used in self.used_libraries() {
            writeln!(out, "#include <mikros/midl/{used}.h>").unwrap();
        }
        out.push_str("\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n");
        self.declarations(&mut out);
        writeln!(out, "#ifdef __cplusplus\n}}\n#endif\n\n#endif").unwrap();
        out
    }

    /// The other libraries whose declarations this one's types name.
    fn used_libraries(&self) -> BTreeSet<String> {
        let mut used = BTreeSet::new();
        let mut note = |ty: &Type| {
            visit(ty, &mut |t| match t {
                Type::Named { name, .. } => {
                    used.insert(library_of(name).to_string());
                }
                Type::Endpoint { protocol, .. } => {
                    used.insert(library_of(protocol).to_string());
                }
                _ => {}
            })
        };
        for decl in &self.library.decls {
            match &decl.kind {
                DeclKind::Const { ty, .. } | DeclKind::Alias(ty) => note(ty),
                DeclKind::Struct(fields) => fields.iter().for_each(|f| note(&f.ty)),
                DeclKind::Union { members, .. } | DeclKind::Table(members) => {
                    members.iter().for_each(|m| note(&m.ty))
                }
                DeclKind::Protocol(methods) => {
                    for m in methods {
                        match &m.kind {
                            MethodKind::TwoWay {
                                request,
                                response,
                                error,
                            } => {
                                request.iter().chain(response).for_each(|f| note(&f.ty));
                                if let Some(e) = error {
                                    note(e);
                                }
                            }
                            MethodKind::OneWay(fields) | MethodKind::Event(fields) => {
                                fields.iter().for_each(|f| note(&f.ty))
                            }
                        }
                    }
                }
                DeclKind::Enum { .. } | DeclKind::Bits { .. } => {}
            }
        }
        used.remove(&self.library.name);
        used
    }

    /// The C name of the declaration with full name `full`.
    fn cname(&self, full: &str) -> String {
        let (library, name) = full.rsplit_once('.').expect("full names have a library");
        format!("{}_{name}", prefix(library))
    }

    /// The C name of a declaration of this library.
    fn own(&self, name: &str) -> String {
        format!("{}_{name}", prefix(&self.library.name))
    }

    fn decl_of(&self, full: &str) -> &DeclKind {
        &self.model.decl(full).expect("checked names exist").kind
    }

    fn fresh(&self, base: &str) -> String {
        let n = self.counter.get();
        self.counter.set(n + 1);
        format!("{base}{n}")
    }

    fn size(&self, ty: &Type) -> u64 {
        self.layout.shape(ty).size
    }

    /// The C type of `ty`, for any type but an array.
    fn ctype(&self, ty: &Type) -> String {
        match ty {
            Type::Bool => "bool".into(),
            Type::Int(int) => int_type(*int).into(),
            Type::F32 => "float".into(),
            Type::F64 => "double".into(),
            Type::String { .. } => "mikros_midl_string_t".into(),
            Type::Vector { .. } => "mikros_midl_vector_t".into(),
            Type::Handle { .. } | Type::Endpoint { .. } => "mikros_handle_t".into(),
            Type::Named { name, optional } => match self.decl_of(name) {
                DeclKind::Struct(_) if *optional => format!("{} *", self.cname(name)),
                _ => self.cname(name),
            },
            Type::Array { .. } => unreachable!("arrays are declared with cdecl"),
        }
    }

    /// The declaration of `name` as a `ty`: `uint32_t name`, `uint8_t
    /// name[4]`, `mikros_gpu_Mode *name`.
    fn cdecl(&self, ty: &Type, name: &str) -> String {
        match ty {
            Type::Array { element, len } => self.cdecl(element, &format!("{name}[{len}]")),
            _ => {
                let t = self.ctype(ty);
                match t.ends_with('*') || name.is_empty() {
                    true => format!("{t}{name}"),
                    false => format!("{t} {name}"),
                }
            }
        }
    }

    /// What a vector of `ty` holds, said in a comment after the field.
    fn element_note(&self, ty: &Type) -> String {
        match ty {
            Type::Vector { element, .. } => format!(" /* of {} */", self.cdecl(element, "")),
            _ => String::new(),
        }
    }
}

/// Calls `f` on `ty` and every type it contains.
fn visit(ty: &Type, f: &mut impl FnMut(&Type)) {
    f(ty);
    if let Type::Vector { element, .. } | Type::Array { element, .. } = ty {
        visit(element, f);
    }
}

fn library_of(full: &str) -> &str {
    full.rsplit_once('.').expect("full names have a library").0
}

/// The C prefix of `library`: its name with underscores for dots.
fn prefix(library: &str) -> String {
    library.replace('.', "_")
}

fn int_type(int: Int) -> &'static str {
    match int {
        Int::I8 => "int8_t",
        Int::I16 => "int16_t",
        Int::I32 => "int32_t",
        Int::I64 => "int64_t",
        Int::U8 => "uint8_t",
        Int::U16 => "uint16_t",
        Int::U32 => "uint32_t",
        Int::U64 => "uint64_t",
    }
}

/// The unsigned C type of `int`'s width, and the runtime's name for it.
fn wire_int(int: Int) -> (&'static str, &'static str) {
    match int.size() {
        1 => ("uint8_t", "u8"),
        2 => ("uint16_t", "u16"),
        4 => ("uint32_t", "u32"),
        _ => ("uint64_t", "u64"),
    }
}

/// `value` as a C constant of `int`.
fn int_literal(int: Int, value: i128) -> String {
    let t = int_type(int);
    match (int.signed(), int.size()) {
        (true, 8) if value == i64::MIN as i128 => "INT64_MIN".into(),
        (true, 8) => format!("INT64_C({value})"),
        (false, 8) => format!("UINT64_C({value})"),
        (true, _) => format!("(({t}){value})"),
        (false, _) => format!("(({t}){value}u)"),
    }
}

/// `name` as a C identifier, with an `_` after it when it is a keyword
/// of C or C++ or a name that the C library defines as a macro.
pub(crate) fn ident(name: &str) -> String {
    const RESERVED: &str = "\
    alignas alignof and and_eq asm assert auto bitand bitor bool break case catch char char16_t \
    char32_t char8_t class co_await co_return co_yield compl concept const const_cast consteval \
    constexpr constinit continue decltype default delete do double dynamic_cast else enum errno \
    explicit export extern false float for friend goto if inline int long mutable namespace new \
    noexcept not not_eq nullptr operator or or_eq private protected public register \
    reinterpret_cast requires restrict return short signed sizeof static static_assert \
    static_cast stderr stdin stdout struct switch template this thread_local throw true try \
    typedef typeid typename union unsigned using virtual void volatile wchar_t while xor xor_eq";
    match RESERVED.split_whitespace().any(|w| w == name) {
        true => format!("{name}_"),
        false => name.to_string(),
    }
}

/// `text` safe inside a C comment.
fn comment(text: &str) -> String {
    text.replace("*/", "* /")
}

/// `doc` as a C comment indented by `indent`, or nothing.
pub(crate) fn doc(doc: &[String], indent: &str) -> String {
    match doc {
        [] => String::new(),
        [line] => format!("{indent}/* {} */\n", comment(line)),
        lines => {
            let mut out = format!("{indent}/* {}\n", comment(&lines[0]));
            for line in &lines[1..] {
                writeln!(out, "{indent} * {}", comment(line)).unwrap();
            }
            writeln!(out, "{indent} */").unwrap();
            out
        }
    }
}

/// `s` as a C string literal.
fn string_literal(s: &str) -> String {
    let mut out = String::from("\"");
    for b in s.bytes() {
        match b {
            b'"' => out.push_str("\\\""),
            b'\\' => out.push_str("\\\\"),
            b'\n' => out.push_str("\\n"),
            0x20..=0x7e => out.push(b as char),
            _ => write!(out, "\\{b:03o}").unwrap(),
        }
    }
    out.push('"');
    out
}

/// `code`, a statement, label or brace on each line, indented four
/// spaces for each brace that is open.
fn indented(code: &str) -> String {
    let mut out = String::new();
    let mut depth = 0usize;
    for line in code.lines() {
        let line = line.trim();
        if line.is_empty() {
            out.push('\n');
            continue;
        }
        let closing = line.starts_with('}');
        if closing {
            depth = depth.saturating_sub(1);
        }
        // The lines of a comment after its first line.
        let lead = if line.starts_with('*') { " " } else { "" };
        writeln!(out, "{}{lead}{line}", "    ".repeat(depth)).unwrap();
        let opens = line.matches('{').count();
        let closes = line.matches('}').count() - usize::from(closing);
        depth = (depth + opens).saturating_sub(closes);
    }
    out
}
