//! Applying the relocations of a position-independent executable that
//! has no dynamic linker, before any Rust code runs.
//!
//! It is written in assembly because compiled code, even checks that
//! debug builds add to pointer reads, may call through entries of the
//! global offset table, which only the relocations make valid.
//!
//! `__mikros_relocate` does nothing for an image that is not `ET_DYN` or
//! has no `PT_DYNAMIC`. Otherwise it applies every `R_X86_64_RELATIVE`
//! relocation of `DT_RELA`, and stops the program with `ud2` at an entry
//! size other than 24, at `DT_REL` or `DT_RELR`, and at any other
//! relocation type. It uses only registers that a call may change.

core::arch::global_asm!(
    ".pushsection .text.__mikros_relocate,\"ax\",@progbits",
    ".globl __mikros_relocate",
    ".hidden __mikros_relocate",
    ".p2align 4",
    "__mikros_relocate:",
    // r8: the ELF header; rdi: the address of the segment at file
    // offset 0, or -1; rsi: the address of PT_DYNAMIC, or 0.
    "lea r8, [rip + __ehdr_start]",
    "movzx eax, word ptr [r8 + 16]",
    "cmp eax, 3",
    "jne 9f",
    "mov rcx, [r8 + 32]",
    "add rcx, r8",
    "movzx r10d, word ptr [r8 + 54]",
    "movzx r11d, word ptr [r8 + 56]",
    "mov rdi, -1",
    "xor esi, esi",
    "1:",
    "test r11, r11",
    "jz 3f",
    "mov eax, [rcx]",
    "cmp eax, 1",
    "jne 2f",
    "cmp qword ptr [rcx + 8], 0",
    "jne 4f",
    "mov rdi, [rcx + 16]",
    "jmp 4f",
    "2:",
    "cmp eax, 2",
    "jne 4f",
    "mov rsi, [rcx + 16]",
    "4:",
    "add rcx, r10",
    "dec r11",
    "jmp 1b",
    "3:",
    "cmp rdi, -1",
    "je 9f",
    "test rsi, rsi",
    "jz 9f",
    // r8: the load bias; rcx: the dynamic section; r9, r10, r11: DT_RELA,
    // DT_RELASZ and DT_RELAENT.
    "sub r8, rdi",
    "lea rcx, [r8 + rsi]",
    "xor r9d, r9d",
    "xor r10d, r10d",
    "mov r11d, 24",
    "5:",
    "mov rax, [rcx]",
    "mov rdx, [rcx + 8]",
    "test rax, rax",
    "jz 6f",
    "cmp rax, 7",
    "cmove r9, rdx",
    "cmp rax, 8",
    "cmove r10, rdx",
    "cmp rax, 9",
    "cmove r11, rdx",
    "cmp rax, 17",
    "je 8f",
    "cmp rax, 36",
    "je 8f",
    "add rcx, 16",
    "jmp 5b",
    "6:",
    "cmp r11, 24",
    "jne 8f",
    "lea rcx, [r8 + r9]",
    "add r10, rcx",
    "7:",
    "cmp rcx, r10",
    "jae 9f",
    "cmp dword ptr [rcx + 8], 8",
    "jne 8f",
    "mov rax, [rcx + 16]",
    "add rax, r8",
    "mov rdx, [rcx]",
    "mov [r8 + rdx], rax",
    "add rcx, 24",
    "jmp 7b",
    "8:",
    "ud2",
    "9:",
    "ret",
    ".popsection",
);
